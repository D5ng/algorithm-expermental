/**
 * BFE.dev - Integer to Roman
 *
 * 133번 로마 숫자를 정수로 변환하는 문제의 반대 문제입니다.
 *
 * 로마 숫자는 다음 7개 기호를 조합해 표현하며, 각 기호에는 고정된 정수 값이 있습니다.
 *
 * | 기호 | I | V | X  | L  | C   | D   | M    |
 * | ---- | - | - | -- | -- | --- | --- | ---- |
 * | 값   | 1 | 5 | 10 | 50 | 100 | 500 | 1000 |
 *
 * 표준 표기법에서는 뺄셈 표기법을 사용합니다. 예를 들어 4는 IIII가 아니라 IV로,
 * 9는 VIIII가 아니라 IX로 표현합니다. 같은 규칙으로 40은 XL, 900은 CM으로 표현합니다.
 *
 * 표준 로마 숫자는 다음 규칙을 따릅니다.
 * - 기호는 왼쪽에서 오른쪽으로 값이 큰 순서부터 나열됩니다.
 * - 왼쪽에서 오른쪽으로 읽을 때, 다음 기호의 값이 현재 기호보다 크면 현재 값을 뺍니다. 그렇지 않으면 더합니다.
 *
 * integerToRoman() 함수를 구현하세요. 입력은 모두 유효한 범위의 정수입니다.
 *
 * @example
 * ```ts
 * integerToRoman(123);
 * 'CXXIII'
 *
 * integerToRoman(1999);
 * 'MCMXCIX'
 *
 * integerToRoman(3420);
 * 'MMMCDXX'
 * ```
 */
export function integerToRoman(num: number) {
	/**
	 * 코드 그대로 설명: 배열 안에 배열이 있고, 0번째 인덱스는 숫자를, 1번째 인덱스에는 로마 문자가 있다.
	 * 이 코드가 맡은 역할: 뺄셈 표기까지 포함한 값-로마 문자 쌍을, 큰 값부터 정렬된 순서로 준비한다
	 * 전체 목적에 기여하는것: 자릿수를 세지않고 올바른 로마 숫자가 나올 수 있도록 보장한다
	 */
	const values = [
		[1000, "M"],
		[900, "CM"],
		[500, "D"],
		[400, "CD"],
		[100, "C"],
		[90, "XC"],
		[50, "L"],
		[40, "XL"],
		[10, "X"],
		[9, "IX"],
		[5, "V"],
		[4, "IV"],
		[1, "I"],
	] as const

	/**
	 * 코드 그대로 설명: 매개변수를 n에 할당한다
	 * 이 코드가 맡은 역할: 아직 로마 숫자로 변환하지 못한 나머지 값을 추적한다
	 * 전체 목적에 기여하는것: 이 값이 0이 될 때까지 루프가 더 처리할 게 남았는지 판단하게 하고, 결국 num 전체가 빠짐없이 로마 숫자로 옮겨지도록 보장한다
	 */
	let n = num
	/**
	 * 코드 그대로 설명: 빈 값을 담는다
	 * 이 코드가 맡은 역할: 로마 문자열을 이어붙일 수 있는 데이터
	 * 전체 목적에 기여하는것: 완성된 로마 문자열을 반환
	 */
	let result = ""

	/**
	 * 코드 그대로 설명: 큰 값부터 정렬된 values를 위에서부터 반복하며, n이 그 값 이상이라면 몫만큼 로마 숫자를 반복해 result에 이어붙이고, n을 나머지로 업데이트한다
	 * 이 코드가 맡은 역할:
	 * 전체 목적에 기여하는것: 로마 숫자를 올바르게 처리하기 위해 값을 처리한다
	 */
	for (const [value, romanChar] of values) {
		if (n >= value) {
			/**
			 * 코드 그대로 설명: n / value로 소수점을 버린 몫만 남긴다
			 * 이 코드가 맡은 역할: 로마 숫자를 몇번 이어붙일건지에 대한 횟수를 말한다
			 * 전체 목적에 기여하는것: 변환된 로마 숫자가 원래 숫자와 같은 값을 갖도록 보장한다
			 */
			const count = Math.floor(n / value)
			/**
			 * 코드 그대로 설명: 로마 문자를 문자열로 변환하고 count만큼 반복하고 result에 할당한다
			 * 이 코드가 맡은 역할: 해당 로마 숫자를 count개수만큼 이어붙인다.
			 * 전체 목적에 기여하는것: 규칙에 맞는 로마 숫자가 나올 수 있도록 보장한다
			 */
			result += romanChar.toString().repeat(count)
			/**
			 * 코드 그대로 설명: n % value 나머지를 구하고 n에 할당한다
			 * 이 코드가 맡은 역할: 나머지 값을 업데이트하여 다음 로마 숫자가 무엇이 나올지 준비한다
			 * 전체 목적에 기여하는것: 이미 표현한 값을 다시 세지 않도록 하기위해 변환 결과가 원래 숫자와 일차하도록 보장한다
			 */
			n = n % value
		}
	}

	return result
}

/**
 * 목적:
 * - 주어진 숫자를 로마 숫자로 변환하는 함수
 *
 * 입력:
 * - 정수
 *
 * 출력:
 * - 로마 숫자로 된 문자열
 *
 * 흐름:
 * [123] 기준
 * 123 / 100 = 1(C)
 * 123 % 100 => 23
 * 23 / 10 => 2(XX)
 * 23 % 20 = 3
 * 3 / 1 => 3(III)
 * 3 % 1 = 0
 *
 * 3420
 * 3420 % 3000(MMM) === 3
 * 3420 / 3000 = 420
 * 420 % 400(CD) === 4
 * 420 / 400 = 20
 * 20 / 10(xx) = 20
 *
 * 1999 기준이라면?
 * 1999 / 1000 = 1 => M
 * 1999 % 1000 = 999
 * 999 / 100 = 9 => CM (천의자리와 백의자리로 구함)
 * 999 % 100 = 99
 * 99 / 10 = 9  => XC (백의자리와 십의자리로 구함)
 * 99 % 10 = 9 => IX
 *
 * 현재 무엇이 문제인걸까?
 * 각 자릿수에 어떤 로마숫자 값이 들어가야하는지를 모르는게 문제인거야.
 * 1(I), 4(IV), 5(V), 9(IX)
 * 10(X), 40(XL), 50(L), 90(XC)
 * 100(C), 400(CD), 500(D), 900(CM)
 * 1000(M)
 *
 * 뒤에서 부터 구한것을 일의자리로 구하고, 루프를 돌 때마다 십의자리로 올라가는 형태라면 가능한데... 처리하는 준비 과정이 복잡해질 것 같아.
 *
 * 처리:
 * 기호는 왼쪽에서 오른쪽으로 값이 큰 순서부터 나열된다. 123 -> CXXIII
 * 왼쪽에서 오른쪽으로 읽을 때 다음 기호의 값이 현재 기호보다 크면 현재 값을 빼고, 그렇지 않으면 더한다
 *
 * 막힌 지점:
 * 각 자릿수에 어떤 로마숫자 값이 들어가야하는지 가늠이 안잡혔다.
 * - 뒤에서부터 구하는 방식
 * - 앞에서부터 구하는 방식
 *
 * 위 두가지를 생각해보니 일의자리...천의자리까지 어떻게 계산해야할지, 만약 하나하나 값을 정한다면 가능하겠지만 처리 과정이 너무 복잡할 것 같다는 생각이 들었음.
 */
